                      when rnd.num >  0.5 and rnd.num <= 0.6 then 'Generics Gestapo'
                      when rnd.num >  0.6 and rnd.num <= 0.7 then 'Insurance Inquisition'
                      when rnd.num >  0.7 and rnd.num <= 0.8 then 'Manufacturers Ministry'
                      when rnd.num >  0.8 and rnd.num <= 0.9 then 'Copay Committee'
                      when rnd.num >  0.8 and rnd.num <= 0.9 then 'Prescriber Penmanship Program'
                      when rnd.num >  0.9 and rnd.num <= 1.0 then 'Section of Symptoms and Side Effects'
                      end as reg
          from (
                select rand(checksum(newid()))  
               ) rnd (num)          
         ) rg
    cross apply (
                 select CHAR(65+((51+0.5+CAST(rand(checksum(newid()))*52 AS INT)*0.5)%26))
                      + CHAR(65+((51+0.5+CAST(rand(checksum(newid()))*52 AS INT)*0.5)%26))
                      + CHAR(65+((51+0.5+CAST(rand(checksum(newid()))*52 AS INT)*0.5)%26))
                      + right('0000' + REPLACE(cast(rand(checksum(newid())) as varchar(20)),'.',''),4)
                      + right('0000' + REPLACE(cast(rand(checksum(newid())) as varchar(20)),'.',''),4) 
