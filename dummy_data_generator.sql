       ,rg.reg AS REGLTG_BDY
       ,pp.F_NM AS MBR_FRST_NM
       ,pp.L_NM AS MBR_LAST_NM 
       ,dob.b_dt AS DOB
       ,aw.add1 AS ADRS
       ,aw.add2 AS ADRS_2
       ,pl.C_NM AS MBR_CITY
       ,pl.S_NM AS MBR_ST
       ,zp.zip AS MBR_ZIP_CD
       ,hid.hcid AS HCID
       ,try_cast(abs(checksum(newid())) as bigint) AS MCID
       ,case when rand(checksum(newid())) <= 0.005 then 'Y' else 'N' end AS ZP_DRUG_DLVR
    from (
          select top 1 F_NM, L_NM
          from #people
          order by newid()
         ) as pp
    cross apply     
         (
          SELECT top 1 DATEADD(DAY, RAND(CHECKSUM(NEWID()))*(1+DATEDIFF(DAY, @StartDate, @EndDate)),@StartDate)
         ) as dob (b_dt)
    cross apply
         (
          select top 1 C_NM, S_NM
          from #place
          order by newid()
         ) as pl  
    cross apply
         (
          select top 1 concat(zip3.ZIP3 , right('00'+cast(checksum(newid()) as varchar(20)),2)) as zip
          from #zip_3 zip3
          where zip3.S_NM = pl.S_NM
          order by newid()             
         ) zp (zip)
    cross apply
         (
          select top 1 add1, add2
          from #adrs
          order by newid() 
         ) aw
    cross apply
         (
          select case when rnd.num >= 0.0 and rnd.num <= 0.1 then 'Route of Administration'
